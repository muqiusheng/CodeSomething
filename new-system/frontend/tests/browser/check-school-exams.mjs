async function exported(selector,file) {
  // Inspect the generated Blob in Chromium because agent-browser's disk download can be canceled on Windows.
  await evaluate("(()=>{const click=HTMLAnchorElement.prototype.click;window.examExport=null;HTMLAnchorElement.prototype.click=function(){if(!this.download)return click.call(this);HTMLAnchorElement.prototype.click=click;const name=this.download;fetch(this.href).then(response=>response.text()).then(data=>{window.examExport={name,data};});};return true;})()");
  await click(selector);
  await until('typeof window.examExport?.data==="string"');
  const {name,data}=await evaluate('window.examExport');
  assert.ok(name.endsWith(file.slice(file.lastIndexOf('.'))));
  writeFileSync(join(output,file),data,'utf8');
  return data;
}
